-- ============================================================
-- V2 : repair_shop 재적재 멱등성 확보
-- ============================================================
--
-- 배경
--   서울시 자전거 편의시설 API(tvBicycleEtc)에서 수리센터를 적재하려는데
--   repair_shop에 고유 식별자가 없다. 소스도 고유키를 주지 않는다
--   (FCLT_ID는 자치구가 제멋대로 부여해 "광진구_자전거종합서비스센터" 같은
--    한글 문자열부터 "11103419_1740730605325" 같은 타임스탬프 조합까지 섞여 있고,
--    같은 시설이 갱신되면 값이 바뀔 수 있어 신뢰할 수 없다).
--
--   그래서 route_facility와 같은 방식으로 (이름, 좌표)를 자연키로 삼는다.
--   ON CONFLICT DO NOTHING으로 재실행해도 행이 늘지 않는다.
--
--   shop_name은 NOT NULL이라 route_facility 때와 달리 COALESCE가 필요 없다.
-- ============================================================

CREATE UNIQUE INDEX uq_repair_shop_natural
    ON repair_shop (shop_name, geom);

COMMENT ON INDEX uq_repair_shop_natural IS
    '재적재 멱등성. 소스에 신뢰할 만한 고유키가 없어 (이름, 좌표)를 자연키로 쓴다.';
